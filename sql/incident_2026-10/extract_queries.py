"""Extract the SQL embedded in TMDL partitions into standalone .sql files for SSMS testing.

For each table, writes two files:
  queries/<table>__current.sql   - query from the working tree (what is published now)
  queries/<table>__before.sql    - query from BASELINE_COMMIT (before the Aug-30 changes)

Every file gets a header that turns on STATISTICS IO/TIME and labels the run,
so the Messages tab in SSMS shows reads/CPU per run.

It also builds the ready-to-run SSMS files (no SQLCMD mode needed):
  02_measure_all.sql                     - all queries, before + current, one after another
  03b_reader_read_committed.sql          - factPurchaseExpenses as the refresh runs it today
  03b_reader_read_uncommitted.sql        - same query with the proposed READ UNCOMMITTED fix

Usage (from the repo root):  python sql/incident_2026-10/extract_queries.py
"""
import re
import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
OUT = HERE / "queries"
STG_SERVER = r"ADM-SQL2020\ADMNEW"

# Stops every following batch (NOEXEC stays on across GO) when not connected to STG.
GUARD = (
    f"IF @@SERVERNAME <> N'{STG_SERVER}'\n"
    "BEGIN\n"
    "    RAISERROR(N'This is not the STG server - stopping. Reconnect to STG and run again.', 16, 1);\n"
    "    SET NOEXEC ON;\n"
    "END\n"
    "GO\n\n"
)

# Last commit before the Aug-30 query changes (ed51663^).
BASELINE_COMMIT = "5b60782"

TABLES = [
    "factPurchaseExpenses",
    "factGain",
    "dimPurchaseOrderNumber",
    "dimSubPurchaseOrderNumber",
    "factOrders",
]

CURRENT_DIR = "PBI/SM/ADM - DS.SemanticModel/definition/tables"
BASELINE_DIR = "SM/ADM - DS.SemanticModel/definition/tables"  # folder layout before 7b6afd7


def m_query_to_sql(tmdl: str) -> str:
    """Pull the first Query="..." string out of a TMDL file and decode M escapes."""
    start = tmdl.find('[Query="')
    if start < 0:
        raise ValueError("no [Query=\"...\"] found")
    i = start + len('[Query="')
    buf = []
    while i < len(tmdl):
        ch = tmdl[i]
        if ch == '"':
            if tmdl[i + 1:i + 2] == '"':  # "" is an escaped quote in M
                buf.append('"')
                i += 2
                continue
            break
        buf.append(ch)
        i += 1
    s = "".join(buf)
    s = s.replace("#(cr)#(lf)", "\n").replace("#(lf)", "\n").replace("#(cr)", "\n").replace("#(tab)", "\t")
    s = s.replace("#(#)", "#")
    s = re.sub(r"#\(([0-9A-Fa-f]{4,6})\)", lambda m: chr(int(m.group(1), 16)), s)
    return s


def header(table: str, version: str) -> str:
    return (
        f"-- {table} ({version}) - extracted from TMDL by extract_queries.py\n"
        "-- Run on STG only. Before running: Query > Query Options > Results > Grid >\n"
        "-- tick 'Discard results after execution', so SSMS does not render the rows.\n"
        f"PRINT '===== {table} | {version} =====';\n"
        "SET STATISTICS IO, TIME ON;\n"
        "GO\n\n"
    )


def footer() -> str:
    return "\nGO\nSET STATISTICS IO, TIME OFF;\nGO\n"


def block(table: str, version: str, sql: str) -> str:
    return header(table, version) + sql + footer()


def save(path: Path, text: str) -> None:
    # utf-8-sig so SSMS opens the Hebrew text correctly
    path.write_text(text, encoding="utf-8-sig")
    print(f"  {path.relative_to(REPO)}")


MEASURE_HEADER = """-- 02 | Measure every query, before vs current - STG only. GENERATED by extract_queries.py.
--
-- How to run (no SQLCMD mode needed):
--   1. Query > Query Options > Results > Grid > tick "Discard results after execution"
--   2. Run the whole file TWICE. Use the numbers from the 2nd run (the 1st one warms the cache).
--   3. Messages tab: each block starts with "===== table | version =====".
--      Copy "logical reads" of the big tables + "CPU time / elapsed time" into README.md.

"""

READER_HEADER = """-- 03b | Our refresh query as the reader ({iso}) - STG only. GENERATED by extract_queries.py.
--
-- Results grid: tick "Discard results after execution".
-- Used by the lock simulation - see README.md, steps 3-5.

"""


def main() -> None:
    OUT.mkdir(exist_ok=True)
    queries = {}  # (table, version) -> sql
    for t in TABLES:
        print(t)
        cur = (REPO / CURRENT_DIR / f"{t}.tmdl").read_text(encoding="utf-8")
        queries[(t, "current")] = m_query_to_sql(cur)
        try:
            old = subprocess.run(
                ["git", "-C", str(REPO), "show", f"{BASELINE_COMMIT}:{BASELINE_DIR}/{t}.tmdl"],
                check=True, capture_output=True,
            ).stdout.decode("utf-8")
            queries[(t, "before")] = m_query_to_sql(old)
        except subprocess.CalledProcessError:
            print(f"  (no baseline version of {t} at {BASELINE_COMMIT})")
        for v in ("before", "current"):
            if (t, v) in queries:
                save(OUT / f"{t}__{v}.sql", block(t, v, queries[(t, v)]))

    print("runner files")
    measure = MEASURE_HEADER + GUARD + "".join(
        block(t, v, queries[(t, v)]) for t in TABLES for v in ("before", "current") if (t, v) in queries
    ) + "SET NOEXEC OFF;\nGO\n"
    save(HERE / "02_measure_all.sql", measure)

    expenses = queries[("factPurchaseExpenses", "current")]
    for iso, name in (("READ COMMITTED", "read_committed"), ("READ UNCOMMITTED", "read_uncommitted")):
        reader = (
            READER_HEADER.format(iso=iso) + GUARD
            + f"SET TRANSACTION ISOLATION LEVEL {iso};\n"
            + f"PRINT CONCAT('Reader SPID ', @@SPID, ' | {iso} | start ', CONVERT(varchar(12), SYSDATETIME(), 114));\nGO\n\n"
            + block("factPurchaseExpenses", f"current, {iso}", expenses)
            + "PRINT CONCAT('Reader end ', CONVERT(varchar(12), SYSDATETIME(), 114));\n"
            + "SET TRANSACTION ISOLATION LEVEL READ COMMITTED;\nSET NOEXEC OFF;\nGO\n"
        )
        save(HERE / f"03b_reader_{name}.sql", reader)


if __name__ == "__main__":
    main()
